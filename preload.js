const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('assistant', {
  platform: process.platform,
  setShape: (rects) => ipcRenderer.send('set-shape', rects),
  dragStart: (type) => ipcRenderer.send('drag-start', type),
  dragBy: (dx, dy) => ipcRenderer.invoke('drag-by', { dx, dy }),
  dragMove: (dx, dy) => ipcRenderer.send('drag-move', { dx, dy }),
  dragEnd: () => ipcRenderer.send('drag-end'),
  showMenu: () => ipcRenderer.send('show-menu'),
  clicked: () => ipcRenderer.send('character-clicked'),
  onCharacter: (fn) => ipcRenderer.on('character', (_e, c) => fn(c)),
  onCursor: (fn) => ipcRenderer.on('cursor', (_e, p) => fn(p)),
  onSize: (fn) => ipcRenderer.on('size', (_e, s) => fn(s)),
  resizeBy: (step) => ipcRenderer.send('resize-by', step),
  onSay: (fn) => ipcRenderer.on('say', (_e, msg) => fn(msg)),
  onReact: (fn) => ipcRenderer.on('react', (_e, name) => fn(name)),
  onTimer: (fn) => ipcRenderer.on('timer', (_e, t) => fn(t)),
  onXp: (fn) => ipcRenderer.on('xp', (_e, x) => fn(x)),
  onOutside: (fn) => ipcRenderer.on('outside-click', () => fn()),
  stopTimer: () => ipcRenderer.send('settings:focus'),
  cardAction: (id) => ipcRenderer.send('card-action', id),
  todoAction: (id, op, title) => ipcRenderer.invoke('todo:action', { id, op, title }),
  todoAdd: (title, goalId) => ipcRenderer.invoke('todo:add', { title, goalId }),
  ask: {
    submit: (text) => ipcRenderer.invoke('ask:submit', text),
    screen: (req) => ipcRenderer.invoke('ask:screen', req),
    screenModes: () => ipcRenderer.invoke('ask:screen-modes'),
    addTodos: (items) => ipcRenderer.invoke('ask:add-todos', items),
    onReveal: (fn) => ipcRenderer.on('panel:reveal', () => fn()),
    onRunScreen: (fn) => ipcRenderer.on('ask:run-screen', (_e, req) => fn(req || {})),
    search: (engine, query) => ipcRenderer.send('ask:search', { engine, query }),
    voice: () => ipcRenderer.send('ask:voice'),
    link: (url) => ipcRenderer.send('ask:link', url),
    close: () => ipcRenderer.send('ask:close'),
    onFocus: (fn) => ipcRenderer.on('ask:focus', () => fn()),
  },
  snip: {
    onImage: (fn) => ipcRenderer.on('snip:image', (_e, url) => fn(url)),
    done: (rect) => ipcRenderer.send('snip:done', rect),
  },
  login: (email, password) => ipcRenderer.invoke('login', { email, password }),
  settings: {
    get: () => ipcRenderer.invoke('settings:get'),
    onUpdate: (fn) => ipcRenderer.on('settings:update', (_e, s) => fn(s)),
    setCharacter: (name) => ipcRenderer.send('settings:character', name),
    setAccessory: (id) => ipcRenderer.send('settings:accessory', id),
    setRemind: (min) => ipcRenderer.send('settings:remind', min),
    setAutoStart: (on) => ipcRenderer.send('settings:autostart', on),
    setSize: (v) => ipcRenderer.send('settings:size', v),
    setHealth: (key, on) => ipcRenderer.send('settings:health', { key, on }),
    focus: () => ipcRenderer.send('settings:focus'),
    setFocusMinutes: (m) => ipcRenderer.send('settings:focus-minutes', m),
    connectClaude: (action) => ipcRenderer.invoke('connect:claude', action),
    remoteSet: (on) => ipcRenderer.invoke('remote:set', on),
    remoteCopy: () => ipcRenderer.send('remote:copy'),
    remoteReset: () => ipcRenderer.invoke('remote:reset'),
    schoolSearch: (name) => ipcRenderer.invoke('school:search', name),
    schoolSet: (patch) => ipcRenderer.send('school:set', patch),
    schoolKey: (key) => ipcRenderer.invoke('school:key', key),
    onReveal: (fn) => ipcRenderer.on('panel:reveal', () => fn()),
    ask: () => ipcRenderer.send('settings:ask'),
    aiSaveKey: (provider, key) => ipcRenderer.invoke('ai:save-key', { provider, key }),
    placeSearch: (name) => ipcRenderer.invoke('settings:place-search', name),
    setPlace: (p) => ipcRenderer.send('settings:place', p),
    toggle: (key, on) => ipcRenderer.send('settings:toggle', { key, on }),
    brief: () => ipcRenderer.send('settings:brief'),
    aiClearKey: (provider) => ipcRenderer.send('ai:clear-key', provider),
    aiSet: (patch) => ipcRenderer.send('ai:set', patch),
    aiKeyPage: (provider) => ipcRenderer.send('ai:key-page', provider),
    importImage: () => ipcRenderer.send('settings:import'),
    openFolder: () => ipcRenderer.send('settings:folder'),
    removeImage: (name) => ipcRenderer.send('settings:remove-image', name),
    today: () => ipcRenderer.send('settings:today'),
    refresh: () => ipcRenderer.send('settings:refresh'),
    login: () => ipcRenderer.send('settings:login'),
    logout: () => ipcRenderer.send('settings:logout'),
    close: () => ipcRenderer.send('settings:close'),
    quit: () => ipcRenderer.send('settings:quit'),
  },
});
